// ============================================
// سيرفر HTTP محلي باستخدام Node.js
// بيخدم ملفات الموقع الثابتة (HTML, CSS, Images)
// ============================================

// نستدعي مكتبة http المدمجة في Node.js عشان ننشئ السيرفر
const http = require('http');

// نستدعي مكتبة fs (File System) عشان نقرأ الملفات من القرص
const fs = require('fs');

// نستدعي مكتبة path عشان نتعامل مع مسارات الملفات بشكل آمن عبر الأنظمة
const path = require('path');

// ============================================
// إعدادات السيرفر
// ============================================

// رقم البورت اللي هيفتح عليه السيرفر (localhost:8000)
const PORT = 8000;

// ============================================
// خريطة أنواع الملفات (MIME Types)
// بنوسعها عشان المتصفح يعرف نوع المحتوى اللي بيستقبله
// ============================================
const mime = {
  '.html': 'text/html',        // صفحات الويب
  '.css': 'text/css',          // ملفات التنسيق
  '.js': 'text/javascript',    // ملفات الجافاسكريبت
  '.png': 'image/png',         // صور PNG
  '.jpg': 'image/jpeg',        // صور JPG
  '.jpeg': 'image/jpeg',       // صور JPEG
  '.svg': 'image/svg+xml',     // صور SVG (رسوميات متجهية)
  '.ico': 'image/x-icon',      // أيقونات الموقع
};

// ============================================
// إنشاء السيرفر
// ============================================
http.createServer((req, res) => {
  
  // ----------------------------------------
  // 1. تحديد الملف المطلوب
  // ----------------------------------------
  
  // بنفك تشفير الـ URL (عشان لو فيه رموز عربية أو خاصة)
  // وبنفصل الـ Query String (الـ ? والبراميترز) عن المسار الأساسي
  const urlPath = decodeURIComponent(req.url.split('?')[0]);
  
  // لو المسار هو "/" (الصفحة الرئيسية)، بنوجه الطلب لملف index.html
  // غير كده، بنضيف المسار المطلوب لمسار المجلد الحالي
  const filePath = path.join(__dirname, urlPath === '/' ? 'index.html' : urlPath);

  // ----------------------------------------
  // 2. حماية من الوصول لملفات خارج المجلد
  // ----------------------------------------
  
  // بنتأكد إن الملف المطلوب جوا مجلد المشروع (مش محاولة الوصول لملفات النظام أو خارج المشروع)
  // ده بيمنع هجمات Directory Traversal مثلاً: ../../../etc/passwd
  if (!filePath.startsWith(__dirname)) {
    
    // نرجع خطأ 403 (Forbidden) يعني ممنوع
    res.writeHead(403);
    res.end('Forbidden: Access denied'); // رسالة للمستخدم إن الوصول مرفوض
    return; // نخرج من الدالة عشان ما نكملش قراءة ملفات خطيرة
  }

  // ----------------------------------------
  // 3. قراءة الملف وإرساله للمتصفح
  // ----------------------------------------
  
  // بنقرأ الملف كـ Buffer (بيانات خام)
  fs.readFile(filePath, (err, data) => {
    
    // لو في خطأ (الملف مش موجود مثلاً)
    if (err) {
      
      // نرجع خطأ 404 (Not Found)
      res.writeHead(404);
      res.end('404: File Not Found'); // الصفحة غير موجودة
      
      // نسجل الخطأ في الكونسول للمساعدة في التصحيح
      console.error(`Error loading ${filePath}:`, err.code);
      return;
    }
    
    // ----------------------------------------
    // لو الملف موجود وتمام
    // ----------------------------------------
    
    // بنجيب امتداد الملف (مثلاً: .html أو .css) ونحوله لحروف صغيرة
    const ext = path.extname(filePath).toLowerCase();
    
    // بنجيب الـ MIME Type المناسب من الخريطة اللي فوق
    // لو الامتداد مش معروف، بنرجبه كـ application/octet-stream (بيانات خام)
    const contentType = mime[ext] || 'application/octet-stream';
    
    // نرجع رد ناجح (200 OK) مع تحديد نوع المحتوى في الهيدرز
    res.writeHead(200, { 
      'Content-Type': contentType 
    });
    
    // نبعت ملف المستخدم للمتصفح (ده رد الفعل النهائي)
    res.end(data);
  });

}).listen(PORT, () => {
  
  // ----------------------------------------
  // 4. رسالة التأكيد لما السيرفر يشتغل
  // ----------------------------------------
  
  // طباعة رسالة في الكونسول عشان نعرف إن السيرفر شغال
  console.log(`🚀 Server running at http://localhost:${PORT}`);
  console.log(`✅ Press Ctrl+C to stop the server`);
});
